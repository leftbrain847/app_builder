/** Replace every `__KEY__` placeholder in text files under `dir`. */
export function fillPlaceholders(dir, values) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (name === 'node_modules' || name === '.git') continue;
    if (statSync(p).isDirectory()) fillPlaceholders(p, values);
    else if (/\.(json|ts|mjs|md|html|css|yml|yaml|toml|txt)$/.test(name) || name === '.gitignore') {
      let text = readFileSync(p, 'utf8');
      for (const [k, v] of Object.entries(values)) text = text.split(`__${k}__`).join(v);
      writeFileSync(p, text);
    }
  }
}

/**
 * Copy the platform into an app: the host and SDK source, the spec, the shared
 * settings, a version stamp, the generated wrangler.toml and the shared CI and
 * scripts. The app's own code (src/, test/, app.config.json) is never touched.
 */
export function syncInto(appDir) {
  const app = readJson(join(appDir, 'app.config.json'));
  if (!ID.test(app.id)) throw new Error(`app.config.json id must match ${ID}`);
  const p = platformConfig();
  const dest = join(appDir, 'platform');
  rmSync(dest, { recursive: true, force: true });
  mkdirSync(dest, { recursive: true });
  for (const pkg of ['host', 'client-sdk']) {
    mkdirSync(join(dest, pkg), { recursive: true });
    cpSync(join(ROOT, 'packages', pkg, 'src'), join(dest, pkg, 'src'), { recursive: true });
    const manifest = readJson(join(ROOT, 'packages', pkg, 'package.json'));
    // Inside an app the SDK must resolve the host from the vendored copy, never from the npm registry.
    if (manifest.dependencies?.['@app-builder/host']) manifest.dependencies['@app-builder/host'] = 'file:../host';
    delete manifest.devDependencies;
    delete manifest.scripts;
    writeJson(join(dest, pkg, 'package.json'), manifest);
  }
  cpSync(join(ROOT, 'SPEC.md'), join(dest, 'SPEC.md'));
  cpSync(join(ROOT, 'depth.config.json'), join(dest, 'depth.config.json'));
  writeJson(join(dest, 'platform.config.json'), p);
  writeJson(join(dest, 'VERSION.json'), platformVersion());
  writeFileSync(
    join(dest, 'README.md'),
    '# platform/ (generated)\n\nA stamped copy of [app_builder](https://github.com/leftbrain847/app_builder). Never edit it here: change app_builder, then run `sync` from there. `VERSION.json` says which commit this is.\n',
  );
  writeFileSync(join(appDir, 'wrangler.toml'), renderAppWrangler(app, p));
  const playId = `${p.playPackagePrefix}.${app.id.replace(/-/g, '_')}`;
  for (const rel of ['.github/workflows/app.yml', 'scripts/smoke.mjs', 'scripts/check-play-bundle.mjs', 'scripts/depth-check.mjs']) {
    mkdirSync(dirname(join(appDir, rel)), { recursive: true });
    const text = readFileSync(join(ROOT, 'template', rel), 'utf8').split('__PLAY_APP_ID__').join(playId);
    writeFileSync(join(appDir, rel), text);
  }
  return { app, playId, version: platformVersion() };
}

export function exists(p) {
  return existsSync(p);
}
